#!/usr/bin/env python3
"""Write src/essays.luc from essays/: the short essays Properties shows under a
stage's controls, about the stage and about what is chosen in it (the stock, the
process). Each essay is essays/<kind>/<name>.md: a "# Title" line, then
paragraphs separated by blank lines. Its key is "<kind>/<name>", where name is the
stage's key (recipe.lucb) or the slug of the stock's or process's name (lower
case, runs of anything but letters and digits as one "-"). Run it after editing
an essay: python3 tools/essays.py"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent


def literal(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def read(path):
    lines = path.read_text(encoding='utf-8').strip().split('\n')
    if not lines[0].startswith('# '):
        raise SystemExit(f'{path}: the first line must be "# Title"')
    title = lines[0][2:].strip()
    paragraphs = [' '.join(part.split()) for part in '\n'.join(lines[1:]).strip().split('\n\n')]
    return title, '\n\n'.join(p for p in paragraphs if p)


def main():
    essays = []
    for path in sorted((root / 'essays').glob('*/*.md')):
        key = f'{path.parent.name}/{path.stem}'
        essays.append((key, *read(path)))
    out = ['## Generated by tools/essays.py from essays/; edit the essays, not this file.',
           '## The essays Properties shows under a stage\'s controls, by key: "stage/<key>",',
           '## "stock/<slug>" or "process/<slug>" (essays.slug of the name).',
           '',
           '## The slug of `name`: lower case, runs of anything but letters and digits as one "-".',
           'pub func slug(name: str) -> str:',
           '    var out = ""',
           '    var gap = false',
           '    for letter in name.lower().characters():',
           '        if "abcdefghijklmnopqrstuvwxyz0123456789".contains(letter):',
           '            if gap and out != "":',
           '                out = out + "-"',
           '            out = out + letter',
           '            gap = false',
           '        else:',
           '            gap = true',
           '    return out',
           '']
    for name, index in (('essay_title', 1), ('essay_text', 2)):
        out.append(f'## The essay {"title" if index == 1 else "text"} for `key`, or "".')
        out.append(f'pub func {name}(key: str) -> str:')
        out.append('    match key:')
        for essay in essays:
            out.append(f'        {literal(essay[0])}:')
            out.append(f'            return {literal(essay[index])}')
        out.append('        _:')
        out.append('            return ""')
        out.append('')
    (root / 'src' / 'essays.luc').write_text('\n'.join(out), encoding='utf-8')
    print(f'{len(essays)} essays')


main()
